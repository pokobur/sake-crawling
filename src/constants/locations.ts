/**
 * 会場名や住所の部分一致から代表座標を検索する
 */
export function findPresetCoordinates(locationName: string, address?: string): [number, number] | null {
  const query = `${locationName} ${address || ''}`.trim();

  // 完全一致チェック
  for (const [key, coords] of Object.entries(PRESET_LOCATIONS)) {
    if (query.includes(key) || key.includes(locationName)) {
      return coords;
    }
  }

  return null;
}
